export type SaveStrategyState = { error?: string; success?: boolean };

function slugify(name: string) {
  return (
    name
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, "-")
      .replace(/^-+|-+$/g, "")
      .slice(0, 40) || "strategy"
  );
}

const HANDLE_TYPES = ["AUTO", "MANUAL", "BY_STRATEGY"] as const;

export async function saveStrategy(
  strategyId: string | null,
  _prev: SaveStrategyState,
  formData: FormData,
): Promise<SaveStrategyState> {
  const { workspace, session, role } = await requireActiveWorkspace();

  if (strategyId) {
    const check = await checkStrategyPermission(session.user.id, role, strategyId, "edit_execute");
    if (!check.ok) return { error: check.error };
  } else if (!meetsLevel(workspaceRoleStrategyLevel(role), "edit_execute")) {
    return { error: "Your role can't create strategies." };
  }

  const name = formData.get("name");
  const market = formData.get("market");
  const handleType = formData.get("handleType");
  const description = formData.get("description");
  const defaultSymbol = formData.get("defaultSymbol");
  const requestedSlug = formData.get("slug");
  const coolDownPeriodRaw = formData.get("coolDownPeriod");
  const maxTriggersPerDayRaw = formData.get("maxTriggersPerDay");
  const isGlobal = formData.get("isGlobal") === "on";
  // One checkbox per account, so getAll — absent entirely when the form has no
  // account picker at all, which must not be read as "unlink everything".
  const accountIds = formData.getAll("accountIds").filter((v): v is string => typeof v === "string");
  const hasAccountField = formData.has("accountsFieldPresent");

  if (typeof name !== "string" || name.trim().length === 0) {
    return { error: "Name is required." };
  }
  if (market !== "forex" && market !== "indian_options" && market !== "indian_equity") {
    return { error: "Pick a market." };
  }
  if (typeof handleType !== "string" || !HANDLE_TYPES.includes(handleType as (typeof HANDLE_TYPES)[number])) {
    return { error: "Pick a handle type." };
  }

  let coolDownPeriod: number | null = null;
  if (typeof coolDownPeriodRaw === "string" && coolDownPeriodRaw.trim()) {
    const n = Number(coolDownPeriodRaw);
    if (!Number.isFinite(n) || n < 0) return { error: "Cooldown must be a non-negative number of seconds." };
    coolDownPeriod = Math.round(n);
  }

  let maxTriggersPerDay: number | null = null;
  if (typeof maxTriggersPerDayRaw === "string" && maxTriggersPerDayRaw.trim()) {
    const n = Number(maxTriggersPerDayRaw);
    if (!Number.isFinite(n) || n <= 0) return { error: "Max triggers/day must be a positive number." };
    maxTriggersPerDay = Math.round(n);
  }

  // Slug is globally unique across the whole product, not per-workspace —
  // the webhook payload carries only the slug with no workspace id.
  const isAutoGenerated = !(typeof requestedSlug === "string" && requestedSlug.trim());
  const baseSlug = isAutoGenerated ? slugify(name) : slugify(requestedSlug as string);

  async function isTaken(candidate: string) {
    const [existing] = await db
      .select({ id: strategies.id })
      .from(strategies)
      .where(
        strategyId
          ? and(eq(strategies.slug, candidate), ne(strategies.id, strategyId))
          : eq(strategies.slug, candidate),
      )
      .limit(1);
    return Boolean(existing);
  }

  let slug = baseSlug;
  if (isAutoGenerated) {
    // Auto-generated duplicates get a numeric suffix rather than an error —
    // matches the webhook guide's slug rules ("eurusd-ema-1"). A slug the
    // user typed by hand still hard-errors below, so they can pick their own.
    let suffix = 1;
    while (await isTaken(slug)) {
      slug = `${baseSlug}-${suffix}`;
      suffix += 1;
    }
  } else if (await isTaken(slug)) {
    return { error: `Slug "${slug}" is already in use.` };
  }

  const values = {
    name: name.trim(),
    market: market as Market,
    handleType: handleType as (typeof HANDLE_TYPES)[number],
    description: typeof description === "string" && description.trim() ? description.trim() : null,
    defaultSymbol: typeof defaultSymbol === "string" && defaultSymbol.trim() ? defaultSymbol.trim().toUpperCase() : null,
    slug,
    coolDownPeriod,
    maxTriggersPerDay,
    isGlobal,
  };

  try {
    if (strategyId) {
      await db
        .update(strategies)
        .set({ ...values, updatedAt: new Date() })
        .where(and(eq(strategies.id, strategyId), eq(strategies.workspaceId, workspace.id)));
      if (hasAccountField) {
        await writeLinkedAccounts(strategyId, accountIds, workspace.id);
      }
      await logAudit({
        workspaceId: workspace.id,
        actorId: session.user.id,
        action: "strategy.updated",
        summary: `Updated strategy "${values.name}" (/${values.slug})`,
      });
    } else {
      const newId = crypto.randomUUID();
      await db.insert(strategies).values({
        webhookSecret: generateWebhookSecret(),
        id: newId,
        workspaceId: workspace.id,
        createdBy: session.user.id,
        ...values,
      });
      // Linking at create time is the whole point of the picker — without this
      // a new strategy has no accounts and silently dispatches nowhere until
      // someone opens the separate "Linked accounts" dialog.
      if (accountIds.length > 0) {
        await writeLinkedAccounts(newId, accountIds, workspace.id);
      }
      await logAudit({
        workspaceId: workspace.id,
        actorId: session.user.id,
        action: "strategy.created",
        summary: `Created strategy "${values.name}" (/${values.slug})`,
      });
    }
  } catch (error) {
    return { error: error instanceof Error ? error.message : "Could not save strategy." };
  }

  revalidatePath("/dashboard/monarch/strategies");
  return { success: true };
}

export async function toggleStrategyStatus(strategyId: string): Promise<void> {
  const { workspace, session, role } = await requireActiveWorkspace();
  const check = await checkStrategyPermission(session.user.id, role, strategyId, "view_execute");
  if (!check.ok) return;

  const [row] = await db
    .select({ status: strategies.status, name: strategies.name })
    .from(strategies)
    .where(and(eq(strategies.id, strategyId), eq(strategies.workspaceId, workspace.id)))
    .limit(1);
  if (!row) return;

  const nextStatus = row.status === "active" ? "paused" : "active";
  await db
    .update(strategies)
    .set({ status: nextStatus, updatedAt: new Date() })
    .where(eq(strategies.id, strategyId));

  await logAudit({
    workspaceId: workspace.id,
    actorId: session.user.id,
    action: nextStatus === "paused" ? "strategy.paused" : "strategy.activated",
    summary: `${nextStatus === "paused" ? "Paused" : "Activated"} strategy "${row.name}"`,
  });

  revalidatePath("/dashboard/monarch/strategies");
}

export async function deleteStrategy(strategyId: string): Promise<void> {
  const { workspace, session, role } = await requireActiveWorkspace();
  const check = await checkStrategyPermission(session.user.id, role, strategyId, "co_owner");
  if (!check.ok) return;

  const [row] = await db
    .select({ name: strategies.name })
    .from(strategies)
    .where(and(eq(strategies.id, strategyId), eq(strategies.workspaceId, workspace.id)))
    .limit(1);
  if (!row) return;

  await db
    .delete(strategies)
    .where(and(eq(strategies.id, strategyId), eq(strategies.workspaceId, workspace.id)));

  await logAudit({
    workspaceId: workspace.id,
    actorId: session.user.id,
    action: "strategy.deleted",
    summary: `Deleted strategy "${row.name}"`,
  });

  revalidatePath("/dashboard/monarch/strategies");
}

/**
 * Replaces a strategy's account links, dropping any id that isn't a broker
 * account of `workspaceId`. Callers must have already authorised the actor
 * against the strategy — this only enforces that the *accounts* are owned, so
 * a tampered form can't link a strategy to another workspace's broker.
 */
async function writeLinkedAccounts(
  strategyId: string,
  accountIds: string[],
  workspaceId: string,
): Promise<void> {
  const ownedAccounts =
    accountIds.length === 0
      ? []
      : await db
          .select({ id: brokerAccounts.id })
          .from(brokerAccounts)
          .where(eq(brokerAccounts.workspaceId, workspaceId));
  const ownedIds = new Set(ownedAccounts.map((a) => a.id));
  const validIds = accountIds.filter((id) => ownedIds.has(id));

  await db.delete(strategyAccounts).where(eq(strategyAccounts.strategyId, strategyId));
  if (validIds.length > 0) {
    await db
      .insert(strategyAccounts)
      .values(validIds.map((accountId) => ({ strategyId, accountId })));
  }
}

export async function setLinkedAccounts(strategyId: string, accountIds: string[]): Promise<void> {
  const { workspace, session, role } = await requireActiveWorkspace();
  const check = await checkStrategyPermission(session.user.id, role, strategyId, "edit_execute");
  if (!check.ok) return;

  const [strategy] = await db
    .select({ id: strategies.id })
    .from(strategies)
    .where(and(eq(strategies.id, strategyId), eq(strategies.workspaceId, workspace.id)))
    .limit(1);
  if (!strategy) return;

  await writeLinkedAccounts(strategyId, accountIds, workspace.id);

  revalidatePath("/dashboard/monarch/strategies");
}

export async function fetchSignalHistory(strategyId: string) {
  const { workspace, session, role } = await requireActiveWorkspace();
  const check = await checkStrategyPermission(session.user.id, role, strategyId, "view");
  if (!check.ok) return [];
  const [strategy] = await db
    .select({ id: strategies.id })
    .from(strategies)
    .where(and(eq(strategies.id, strategyId), eq(strategies.workspaceId, workspace.id)))
    .limit(1);
  if (!strategy) return [];

  const { getSignalHistory } = await import("@/lib/strategies/queries");
  return getSignalHistory(strategyId);
}

/** MANUAL handle-type strategies land here until a human confirms or rejects. */
export async function confirmSignal(signalId: string): Promise<{ error?: string }> {
  const { workspace, session, role } = await requireActiveWorkspace();

  const [row] = await db
    .select({ signal: signals, strategy: strategies })
    .from(signals)
    .innerJoin(strategies, eq(signals.strategyId, strategies.id))
    .where(and(eq(signals.id, signalId), eq(strategies.workspaceId, workspace.id)))
    .limit(1);
  if (!row) return { error: "Signal not found." };
  if (row.signal.status !== "pending_confirmation") return { error: "Signal is no longer pending." };

  const check = await checkStrategyPermission(session.user.id, role, row.strategy.id, "view_execute");
  if (!check.ok) return { error: check.error };

  const parsedFields = (row.signal.parsedFields ?? {}) as Record<string, string>;
  const signal: DispatchableSignal = {
    signalId: row.signal.id,
    action: row.signal.action,
    symbol: row.signal.symbol,
    tag: row.signal.tag,
    quantity: parsedFields.quantity ?? null,
    risk: parsedFields.risk ?? null,
    side: row.signal.side,
    sl: row.signal.sl?.toString() ?? null,
    target: row.signal.target?.toString() ?? null,
    valueType: row.signal.valueType,
    percent: parsedFields.percent ?? null,
    price: row.signal.price?.toString() ?? null,
    comment: parsedFields.comment ?? null,
    basketId: parsedFields.basketid ?? null,
    basketName: parsedFields.basketname ?? null,
    paper: parsedFields.paper ?? null,
  };

  const outcome = await dispatchSignal(
    {
      id: row.strategy.id,
      workspaceId: row.strategy.workspaceId,
      market: row.strategy.market,
      handleType: row.strategy.handleType,
      createdBy: row.strategy.createdBy,
      paperTrading: row.strategy.paperTrading,
      allowEntry: row.strategy.allowEntry,
      allowExit: row.strategy.allowExit,
      allowModify: row.strategy.allowModify,
    },
    signal,
  );

  await db
    .update(signals)
    .set({ status: outcome.status, resultMessage: outcome.resultMessage })
    .where(eq(signals.id, signalId));

  revalidatePath("/dashboard/monarch/strategies");
  return {};
}

export async function rejectSignal(signalId: string): Promise<void> {
  const { workspace, session, role } = await requireActiveWorkspace();

  const [row] = await db
    .select({ id: signals.id, strategyId: signals.strategyId })
    .from(signals)
    .innerJoin(strategies, eq(signals.strategyId, strategies.id))
    .where(and(eq(signals.id, signalId), eq(strategies.workspaceId, workspace.id)))
    .limit(1);
  if (!row) return;

  const check = await checkStrategyPermission(session.user.id, role, row.strategyId, "view_execute");
  if (!check.ok) return;

  await db
    .update(signals)
    .set({ status: "rejected", resultMessage: "rejected by user" })
    .where(eq(signals.id, signalId));

  revalidatePath("/dashboard/monarch/strategies");
}
